function renderCalendar() {
  if (!$("#calendar")) return;

  const target = new Date(card.weddingDate);
  const year = target.getFullYear();
  const month = target.getMonth();
  const firstDay = new Date(year, month, 1).getDay();
  const lastDate = new Date(year, month + 1, 0).getDate();
  const weekdays = ["일", "월", "화", "수", "목", "금", "토"];
  const cells = weekdays.map((day) => `<span class="weekday">${day}</span>`);

  for (let i = 0; i < firstDay; i += 1) {
    cells.push("<span></span>");
  }

  for (let date = 1; date <= lastDate; date += 1) {
    const className = date === target.getDate() ? "wedding" : "";
    cells.push(`<span class="${className}">${date}</span>`);
  }

  $("#calendar").innerHTML = cells.join("");

  const today = new Date();
  const diff = Math.ceil((target - today) / 86400000);
  $("#dDay").textContent = diff >= 0 ? `D-${diff}` : `D+${Math.abs(diff)}`;
}

