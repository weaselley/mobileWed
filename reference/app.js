function setupGuestbook() {
  const key = "mobile-wedding-guestbook";
  const resetKey = "mobile-wedding-guestbook-reset-version";
  const modal = $("#guestbookModal");
  const deleteModal = $("#deleteGuestbookModal");
  const openButton = $("#openGuestbook");
  const form = $("#guestbookForm");
  const deleteForm = $("#deleteGuestbookForm");
  const deleteError = $("#deleteGuestbookError");
  let deleteTargetId = null;
  let passwordDb = {
    legacyDefaultPassword: card.guestbook.legacyDefaultPassword,
    passwords: [],
  };

  function clearCurrentMessagesOnce() {
    if (localStorage.getItem(resetKey) === card.guestbook.resetVersion) return;
    localStorage.removeItem(key);
    localStorage.setItem(resetKey, card.guestbook.resetVersion);
  }

  function createMessageId() {
    if (window.crypto && typeof window.crypto.randomUUID === "function") {
      return window.crypto.randomUUID();
    }

    return `${Date.now()}-${Math.random().toString(16).slice(2)}`;
  }

  function getLegacyMessageId(item) {
    return `legacy-${btoa(unescape(encodeURIComponent(`${item.name || ""}|${item.message || ""}|${item.createdAt || ""}`)))
      .replaceAll("=", "")
      .replaceAll("+", "-")
      .replaceAll("/", "_")}`;
  }

  function read() {
    const items = JSON.parse(localStorage.getItem(key) || "[]");
    let changed = false;

    const normalized = items.map((item) => {
      if (item.id) return item;
      changed = true;
      return {
        ...item,
        id: getLegacyMessageId(item),
      };
    });

    if (changed) write(normalized);
    return normalized;
  }

  function write(items) {
    localStorage.setItem(key, JSON.stringify(items));
  }

  async function loadPasswordDb() {
    try {
      const response = await fetch(card.guestbook.passwordDbUrl, { cache: "no-store" });
      if (!response.ok) return;
      const data = await response.json();
      passwordDb = {
        legacyDefaultPassword:
          data.legacyDefaultPassword || card.guestbook.legacyDefaultPassword,
        passwords: Array.isArray(data.passwords) ? data.passwords : [],
      };
    } catch {
      passwordDb = {
        legacyDefaultPassword: card.guestbook.legacyDefaultPassword,
        passwords: [],
      };
    }
  }

  function getStoredPassword(item) {
    if (item.password) return item.password;

    const matched = passwordDb.passwords.find((entry) => {
      if (entry.id && entry.id === item.id) return true;
      if (entry.name && entry.message) {
        return entry.name === item.name && entry.message === item.message;
      }
      return false;
    });

    return matched ? matched.password : passwordDb.legacyDefaultPassword;
  }

  function formatGuestbookTime(value) {
    if (!value) return "";

    const date = new Date(value);
    if (Number.isNaN(date.getTime())) return "";

    const year = date.getFullYear();
    const month = String(date.getMonth() + 1).padStart(2, "0");
    const day = String(date.getDate()).padStart(2, "0");
    const hour = String(date.getHours()).padStart(2, "0");
    const minute = String(date.getMinutes()).padStart(2, "0");
    return `${year}.${month}.${day} ${hour}:${minute}`;
  }

  function openModal() {
    modal.classList.add("is-open");
    modal.setAttribute("aria-hidden", "false");
    document.body.style.overflow = "hidden";
    form.elements.name.focus();
  }

  function closeModal() {
    modal.classList.remove("is-open");
    modal.setAttribute("aria-hidden", "true");
    document.body.style.overflow = "";
    form.reset();
    openButton.focus();
  }

  function openDeleteModal(id) {
    deleteTargetId = id;
    deleteError.textContent = "";
    deleteModal.classList.add("is-open");
    deleteModal.setAttribute("aria-hidden", "false");
    document.body.style.overflow = "hidden";
    deleteForm.elements.password.focus();
  }

  function closeDeleteModal() {
    deleteTargetId = null;
    deleteModal.classList.remove("is-open");
    deleteModal.setAttribute("aria-hidden", "true");
    document.body.style.overflow = modal.classList.contains("is-open") ? "hidden" : "";
    deleteForm.reset();
  }

  function render() {
    const items = read();
    $("#guestbookList").innerHTML = items.length
      ? items
          .map(
            (item) => `
              <article class="guestbook-card" data-animate>
                <div class="guestbook-card-header">
                  <strong>${escapeHtml(item.name)}</strong>
                  <button class="guestbook-delete" type="button" data-delete-guestbook="${escapeHtml(item.id || "")}">삭제</button>
                </div>
                <span class="guestbook-card-body">${escapeHtml(item.message)}</span>
                ${item.createdAt ? `<time class="guestbook-time" datetime="${escapeHtml(item.createdAt)}">${escapeHtml(formatGuestbookTime(item.createdAt))}</time>` : ""}
              </article>
            `
          )
          .join("")
      : `
        <article class="guestbook-card" data-animate>
          <strong>아직 남겨진 메시지가 없습니다</strong>
          <span>따뜻한 축하를 남겨주세요</span>
        </article>
      `;
    observeAnimated($("#guestbookList"));
  }

  openButton.addEventListener("click", openModal);

  modal.addEventListener("click", (event) => {
    if (event.target.closest("[data-close-modal]")) closeModal();
  });

  deleteModal.addEventListener("click", (event) => {
    if (event.target.closest("[data-close-delete-modal]")) closeDeleteModal();
  });

  $("#guestbookList").addEventListener("click", (event) => {
    const button = event.target.closest("[data-delete-guestbook]");
    if (!button) return;
    openDeleteModal(button.dataset.deleteGuestbook);
  });

  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape" && modal.classList.contains("is-open")) closeModal();
    if (event.key === "Escape" && deleteModal.classList.contains("is-open")) closeDeleteModal();
  });

  form.addEventListener("submit", (event) => {
    event.preventDefault();
    const values = Object.fromEntries(new FormData(event.currentTarget));
    const items = read();
    items.unshift({
      id: createMessageId(),
      name: values.name,
      message: values.message,
      password: values.password,
      createdAt: new Date().toISOString(),
    });
    write(items.slice(0, 8));
    closeModal();
    render();
  });

  deleteForm.addEventListener("submit", (event) => {
    event.preventDefault();
    const values = Object.fromEntries(new FormData(event.currentTarget));
    const items = read();
    const target = items.find((item) => item.id === deleteTargetId);

    if (!target) {
      deleteError.textContent = "삭제할 메시지를 찾을 수 없습니다.";
      return;
    }

    const storedPassword = getStoredPassword(target);

    if (storedPassword !== values.password) {
      deleteError.textContent = "비밀번호가 일치하지 않습니다.";
      return;
    }

    write(items.filter((item) => item.id !== deleteTargetId));
    closeDeleteModal();
    render();
  });

  clearCurrentMessagesOnce();
  loadPasswordDb().then(render);
}

