function setupLightbox() {
  const lightbox = $("#lightbox");
  const image = lightbox.querySelector("img");
  let current = 0;

  function open(index) {
    current = index;
    image.src = card.images.gallery[current];
    lightbox.classList.add("is-open");
    lightbox.setAttribute("aria-hidden", "false");
  }

  function close() {
    lightbox.classList.remove("is-open");
    lightbox.setAttribute("aria-hidden", "true");
  }

  function move(step) {
    current = (current + step + card.images.gallery.length) % card.images.gallery.length;
    image.src = card.images.gallery[current];
  }

  $("#galleryGrid").addEventListener("click", (event) => {
    const button = event.target.closest("[data-photo]");
    if (button) open(Number(button.dataset.photo));
  });

  $(".lightbox-close").addEventListener("click", close);
  $(".lightbox-prev").addEventListener("click", () => move(-1));
  $(".lightbox-next").addEventListener("click", () => move(1));
  lightbox.addEventListener("click", (event) => {
    if (event.target === lightbox) close();
  });
}

