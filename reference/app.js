function setupScrollReveal() {
  if (!("IntersectionObserver" in window)) {
    $$("[data-animate]").forEach((node) => node.classList.add("is-visible"));
    return;
  }

  revealObserver = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        entry.target.classList.add("is-visible");
        revealObserver.unobserve(entry.target);
      });
    },
    {
      root: null,
      threshold: 0.18,
      rootMargin: "0px 0px -8% 0px",
    }
  );

  observeAnimated(document);
}

function observeAnimated(root) {
  const scope = root || document;
  const animated = [...scope.querySelectorAll("[data-animate]")];

  animated.forEach((node) => {
    const group = node.closest("[data-animate-group], [data-animate-list]");
    const siblings = group ? [...group.querySelectorAll("[data-animate]")] : animated;
    const index = siblings.indexOf(node);
    node.style.setProperty("--reveal-delay", `${Math.max(index, 0) * 110}ms`);

    if (node.classList.contains("is-visible")) return;
    if (revealObserver) revealObserver.observe(node);
  });
}

function setupPetals() {
  const layer = $("#petalLayer");
  if (!layer || !card.petals.enabled) return;

  const fragment = document.createDocumentFragment();

  for (let i = 0; i < card.petals.count; i += 1) {
    const petal = document.createElement("span");
    petal.className = "petal";
    petal.style.setProperty("--petal-left", `${Math.random() * 100}%`);
    petal.style.setProperty("--petal-size", `${8 + Math.random() * 11}px`);
    petal.style.setProperty("--petal-opacity", `${0.36 + Math.random() * 0.38}`);
    petal.style.setProperty("--petal-blur", `${Math.random() > 0.72 ? 0.8 : 0}px`);
    petal.style.setProperty("--petal-rotate", `${Math.random() * 180}deg`);
    petal.style.setProperty("--petal-drift", `${-60 + Math.random() * 120}px`);
    petal.style.setProperty("--petal-sway", `${8 + Math.random() * 28}px`);
    petal.style.setProperty("--petal-duration", `${8 + Math.random() * 8}s`);
    petal.style.setProperty("--petal-sway-duration", `${2.5 + Math.random() * 2.5}s`);
    petal.style.setProperty("--petal-delay", `${Math.random() * -12}s`);
    fragment.appendChild(petal);
  }

  layer.replaceChildren(fragment);
}

